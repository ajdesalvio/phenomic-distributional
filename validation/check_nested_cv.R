# Rscript validation/check_nested_cv.R NEW_TEST_DIRECTORY
suppressPackageStartupMessages({library(data.table);library(jsonlite);library(glmnet)})
own <- sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE)[1])
root <- normalizePath(file.path(dirname(own),'..'),winslash='/')
source(file.path(root,'src/nested_cv.R'))
a <- commandArgs(TRUE)
if(length(a)!=1L || file.exists(a[1]))stop('Supply a new test directory')
dir.create(a[1],recursive=TRUE);out<-normalizePath(a[1],winslash='/')
checks<-list()
check<-function(label,value){checks[[label]]<<-data.table(Check=label,Pass=isTRUE(value));if(!isTRUE(value))stop(label)}
ids<-sprintf('G%02d',1:40)
f<-v15_fold_ids(ids,5,101123)
check('Balanced genotype folds',max(tabulate(f))-min(tabulate(f))<=1)
check('Fold assignments independent of input order',identical(rev(v15_fold_ids(rev(ids),5,101123)),f))
set.seed(42);x<-matrix(rnorm(40*6),40,6,dimnames=list(ids,paste0('X',1:6)));raw<-x
x[,1]<-1;raw[,1]<-1;x[1,2]<-NA
p<-v15_preprocess_fit(x[1:30,],raw[1:30,]);held<-x[31:40,];held[,2]<-1e6
invisible(v15_preprocess_apply(held,p))
check('Held-out data do not change preprocessing',identical(p,v15_preprocess_fit(x[1:30,],raw[1:30,])))
check('Constant feature excluded',!p$keep[1])
check('Imputation is training-only',p$median[2]==median(x[1:30,2],na.rm=TRUE))
y<-rnorm(30);inner<-v15_fold_ids(ids[1:30],3,101124)
fit<-v15_fit_outer_scenario(x[1:30,],y,x[31:40,],inner,c(0,.5,1),c(1,.1,.01),raw[1:30,])
shifted<-v15_fit_outer_scenario(x[1:30,],y,held,inner,c(0,.5,1),c(1,.1,.01),raw[1:30,])
check('Held-out predictors do not change tuning',isTRUE(all.equal(fit$tuning,shifted$tuning,tolerance=0)))
check('Outer fitter has no test-outcome argument',!'y_test'%in%names(formals(v15_fit_outer_scenario)))
zero<-matrix(0,30,0);fallback<-v15_path(zero,y,0,c(1,.1))
check('Intercept fallback',fallback$intercept_only&&all(v15_path_predict(fallback,matrix(0,2,0),c(1,.1))==mean(y)))
# Tiny fabricated dataset exercises the actual CLI, resume, and source fingerprint.
set.seed(21)
d<-CJ(Env='TXH1.2020',Pedigree=ids,DAP=1:2,Probability=c(.1,.5,.9))
d[,Vegetation.Index:='ExGR'];d[,Quantile.BLUE:=rnorm(.N)]
s<-d[,.(Env,Pedigree,DAP,Probability,Vegetation.Index,Quantile.Raw.Mean=Quantile.BLUE,N.Raw.Finite=2L)]
yield<-data.table(Env='TXH1.2020',Pedigree=ids,Yield.t.ha.BLUE=rnorm(40,10,1))
fwrite(d,file.path(out,'blue.csv'));fwrite(s,file.path(out,'support.csv'));fwrite(yield,file.path(out,'yield.csv'))
inputs<-setNames(lapply(c('blue','support','yield'),function(n)list(path=paste0(n,'.csv'),md5=unname(tools::md5sum(file.path(out,paste0(n,'.csv')))))),c('blue','support','yield'))
write_json(list(inputs=inputs,environments='TXH1.2020'),file.path(out,'config.json'),auto_unbox=TRUE)
runner<-file.path(root,'scripts/maize/run_nested_cv.R');dest<-file.path(out,'runs')
exe<-file.path(R.home('bin'),if(.Platform$OS.type=='windows')'Rscript.exe' else 'Rscript')
args<-c('--vanilla',shQuote(runner),shQuote(file.path(out,'config.json')),shQuote(dest))
code<-system2(exe,args,stdout=file.path(out,'run.log'),stderr=file.path(out,'run.log'));check('Primary CLI on synthetic data',code==0)
cp<-list.files(file.path(dest,'TXH1.2020/checkpoints'),full.names=TRUE);before<-tools::md5sum(cp)
code<-system2(exe,args,stdout=file.path(out,'resume.log'),stderr=file.path(out,'resume.log'));check('Resume leaves completed checkpoints unchanged',code==0&&identical(before,tools::md5sum(cp)))
source(file.path(root,'src/aggregate_nested_cv.R'))
meta<-readRDS(file.path(dest,'TXH1.2020/Run_Manifest_V15.rds'))
invisible(v15a_meta(meta,'TXH1.2020',normalizePath(c(file.path(root,'src/nested_cv.R'),runner),winslash='/')))
check('Aggregator verifies cleaned source fingerprints',TRUE)
writeLines('changed',file.path(out,'yield.csv'))
code<-system2(exe,args,stdout=file.path(out,'changed_input.log'),stderr=file.path(out,'changed_input.log'));check('Changed frozen input rejected',code!=0)
fwrite(rbindlist(checks),file.path(out,'Checks.csv'));print(rbindlist(checks))
